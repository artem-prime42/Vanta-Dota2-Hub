function localizeToast(message) {
  const text = String(message ?? '');
  const language = getLanguage();
  const direct = language === 'ru' ? TOAST_TRANSLATIONS[text] : TOAST_TRANSLATIONS_REVERSE[text];
  if (direct) return direct;
  const patterns = [
    {
      regex: /^(Reading mod|Read mod) (\d+) of (\d+)(\.\.\.|)$/,
      translate: ([, verb, index, total, suffix]) => language === 'ru'
        ? `${verb === 'Read mod' ? 'Прочитан мод' : 'Чтение мода'} ${index} из ${total}${suffix ? '…' : ''}`
        : `${verb} ${index} of ${total}${suffix}`,
    },
    {
      regex: /^Downloading (.+)…$/,
      translate: ([, file]) => language === 'ru' ? `Скачивание ${file}…` : `Downloading ${file}…`,
    },
    {
      regex: /^More than one selected skin targets (.+)\.$/,
      translate: ([, target]) => language === 'ru'
        ? `Несколько выбранных скинов используют общий слот «${target}». Оставлен последний выбранный вариант.`
        : `Several selected skins use the shared slot “${target}”. The most recently selected option was kept.`,
    },
    {
      regex: /^The special patch could not be applied safely: (.+)$/,
      translate: ([, detail]) => language === 'ru' ? `Не удалось безопасно применить специальный патч: ${localizeToast(detail)}` : `The special patch could not be applied safely: ${localizeToast(detail)}`,
    },
    {
      regex: /^Unable to download mod: (.+)$/,
      translate: ([, detail]) => language === 'ru' ? `Не удалось скачать мод: ${detail}` : `Unable to download mod: ${detail}`,
    },
    {
      regex: /^Could not safely check whether Dota 2 is running: (.+)$/,
      translate: ([, detail]) => language === 'ru' ? `Не удалось проверить, запущена ли Dota 2: ${detail}` : `Could not safely check whether Dota 2 is running: ${detail}`,
    },
    {
      regex: /^The selected Dota 2 folder is missing its (.+): (.+)\. Re-detect the game path and verify Dota 2 files in Steam before installing Weather\/Tower patches\.$/,
      translate: ([, label, file]) => language === 'ru'
        ? `В выбранной папке Dota 2 отсутствует файл «${label}»: ${file}. Повторно определите путь и проверьте файлы игры в Steam.`
        : `The selected Dota 2 folder is missing its ${label}: ${file}. Re-detect the game path and verify Dota 2 files in Steam before installing Weather/Tower patches.`,
    },
    {
      regex: /^Could not download patch definition \((\d+)\)\. Try again later\.$/,
      translate: ([, status]) => language === 'ru' ? `Не удалось скачать описание патча (HTTP ${status}). Попробуйте позже.` : `Could not download patch definition (${status}). Try again later.`,
    },
  ];
  for (const { regex, translate } of patterns) {
    const match = text.match(regex);
    if (match) return translate(match);
  }
  return text;
}

function t(key, fallback) {
  const locale = I18N[getLanguage()] || I18N.en;
  const raw = locale[key] || I18N.en[key] || fallback || key;
  return raw;
}

function formatTranslation(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

function setLocalizedText(node, key, values) {
  if (!node) return;
  const value = values ? formatTranslation(t(key), values) : t(key);
  node.textContent = value;
}

function scheduleDataI18n() {
  if (scheduleDataI18n.pending) return;
  scheduleDataI18n.pending = true;
  requestAnimationFrame(() => {
    scheduleDataI18n.pending = false;
    applyDataI18n();
  });
}

function applyDataI18n() {
  if (typeof document === 'undefined') return;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (!key) return;
    const value = t(key);
    if (value) node.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (!key) return;
    const value = t(key);
    if (value) node.placeholder = value;
  });
  document.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const key = node.dataset.i18nTitle;
    if (!key) return;
    const value = t(key);
    if (value) node.title = value;
  });
}

if (typeof MutationObserver !== 'undefined' && typeof document !== 'undefined' && document.body) {
  const i18nObserver = new MutationObserver(() => scheduleDataI18n());
  i18nObserver.observe(document.body, { childList: true, subtree: true });
}

if (typeof window !== 'undefined') {
  window.i18n = { I18N, t, getLanguage, applyDataI18n, formatTranslation, localizeToast };
}

if (typeof document !== 'undefined') {
  requestAnimationFrame(applyDataI18n);
}
